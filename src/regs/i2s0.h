#define I2S0_STATE_TX_IDLE_M (0x00000001U)
#define I2S0_STATE_TX_IDLE_S (0)
#define I2S0_STATE_TX_IDLE_V(v) (((v) << 0) & 0x00000001U)

// I2S ETM configure register
#define I2S0_ETM_CONF_REG ((volatile uint32_t *)(I2S0_BASE + 0x70))
#define I2S0_ETM_CONF_ETM_TX_SEND_WORD_NUM_M (0x000003FFU)
#define I2S0_ETM_CONF_ETM_TX_SEND_WORD_NUM_S (0)
#define I2S0_ETM_CONF_ETM_TX_SEND_WORD_NUM_V(v) (((v) << 0) & 0x000003FFU)
#define I2S0_ETM_CONF_ETM_RX_RECEIVE_WORD_NUM_M (0x000FFC00U)
#define I2S0_ETM_CONF_ETM_RX_RECEIVE_WORD_NUM_S (10)
#define I2S0_ETM_CONF_ETM_RX_RECEIVE_WORD_NUM_V(v) (((v) << 10) & 0x000FFC00U)

// Version control register
#define I2S0_DATE_REG ((volatile uint32_t *)(I2S0_BASE + 0x80))
#define I2S0_DATE_DATE_M (0x0FFFFFFFU)
#define I2S0_DATE_DATE_S (0)
#define I2S0_DATE_DATE_V(v) (((v) << 0) & 0x0FFFFFFFU)

#endif // I2S0_H
